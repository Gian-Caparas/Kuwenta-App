export function getTranslation(language, key, fallback = "") {
  const lang = translations[language] || translations.filipino;
  return lang[key] || fallback || key;
}

export function t(key, language = "filipino", params = {}) {
  let translation = getTranslation(language, key);
  // Simple interpolation: replace {key} with params[key]
  Object.keys(params).forEach((paramKey) => {
    translation = translation.replace(new RegExp(`\\{${paramKey}\\}`, "g"), params[paramKey]);
  });
  return translation;
}

